export default function LegalPage({ kind }: { kind: LegalKind }) {
  const [navSolid, setNavSolid] = useState(true);

  useEffect(() => {
    document.title =
      kind === "privacy"
        ? "Политика конфиденциальности — Period"
        : "Условия пользования — Period";
    window.scrollTo(0, 0);
  }, [kind]);

  useEffect(() => {
    const foot = document.querySelector<HTMLElement>(".foot8");
    if (!foot) return;
    const sync = () => {
      document.documentElement.style.setProperty("--foot8-h", `${foot.offsetHeight}px`);
    };
    sync();
    const ro = new ResizeObserver(sync);
    ro.observe(foot);
    window.addEventListener("resize", sync);
    return () => {
      ro.disconnect();
      window.removeEventListener("resize", sync);
    };
  }, []);

  useEffect(() => {
    const onScroll = () => setNavSolid(window.scrollY > 8);
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, []);

  return (
    <div className="page">
      <SmoothScroll />
      <header className={`site-nav${navSolid ? " is-solid" : ""}`}>
        <div className="wrap nav">
          <a className="brand" href="/">
            <PeriodMark />
            <span className="brand-name">Period</span>
          </a>
          <nav className="nav-links legal-nav-links">
            <a href={kind === "privacy" ? "/terms" : "/privacy"}>
              {kind === "privacy" ? "Условия пользования" : "Политика конфиденциальности"}
            </a>
          </nav>
          <span className="nav-end">
            <a className="btn btn-ghost legal-back" href="/">
              На главную
            </a>
          </span>
        </div>
      </header>
      <div className="site-sheet legal-sheet">
        <div className="silk" aria-hidden="true">
          <Suspense fallback={null}>
            <Silk color="#5c6066" speed={1.6} noiseIntensity={1.05} />
          </Suspense>
        </div>
        <main className="legal-main" id="top">
          <p className="chap">{kind === "privacy" ? "Документ · конфиденциальность" : "Документ · условия"}</p>
          <h1>{TITLES[kind]}</h1>
          <p className="legal-updated">Вступило в силу 28 августа 2026 года</p>
          <div className="legal-doc">{kind === "privacy" ? <PrivacyBody /> : <TermsBody />}</div>
        </main>
      </div>
      <SiteFooter />
    </div>
  );
}
